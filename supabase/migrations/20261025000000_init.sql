create or replace function public.admin_void_donation(p_id uuid, p_reason text) returns void
language plpgsql volatile security definer set search_path = public as $$
declare v_actor text := assert_admin();
begin
  if length(btrim(coalesce(p_reason, ''))) < 3 then raise exception 'REASON_REQUIRED'; end if;
  update donations
  set status = 'anulada', voided_at = now(), voided_by = v_actor, void_reason = btrim(p_reason)
  where id = p_id and status = 'ativa';
  if not found then raise exception 'NOT_FOUND'; end if;
  insert into audit_log(actor, action, donation_id, details)
  values (v_actor, 'doacao_anulada', p_id, jsonb_build_object('motivo', btrim(p_reason)));
end $$;

create or replace function public.admin_restore_donation(p_id uuid) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  v_actor text := assert_admin();
  r record;
begin
  perform 1 from items
  where id in (select item_id from donation_items where donation_id = p_id)
  order by id
  for update;

  for r in
    select di.item_id, di.quantity, i.limit_qty, i.name
    from donation_items di join items i on i.id = di.item_id
    where di.donation_id = p_id
  loop
    if item_committed(r.item_id) + r.quantity > r.limit_qty then
      raise exception 'OVER_LIMIT:%', r.item_id;
    end if;
  end loop;

  update donations
  set status = 'ativa', voided_at = null, voided_by = null, void_reason = null
  where id = p_id and status = 'anulada';
  if not found then raise exception 'NOT_FOUND'; end if;
  insert into audit_log(actor, action, donation_id) values (v_actor, 'doacao_restaurada', p_id);
end $$;

create or replace function public.admin_set_received(p_donation_item_id uuid, p_received boolean) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  v_actor text := assert_admin();
  v_donation uuid;
  v_item text;
begin
  update donation_items di
  set received = p_received,
      received_at = case when p_received then now() end,
      received_by = case when p_received then v_actor end
  where di.id = p_donation_item_id
  returning di.donation_id, (select name from items where id = di.item_id) into v_donation, v_item;
  if not found then raise exception 'NOT_FOUND'; end if;
  insert into audit_log(actor, action, donation_id, details)
  values (v_actor, case when p_received then 'item_recebido' else 'item_recebimento_desfeito' end,
          v_donation, jsonb_build_object('item', v_item));
end $$;

-- Altera a quantidade de um item de uma doação. Quantidade 0 remove o item.
create or replace function public.admin_update_donation_item(p_donation_item_id uuid, p_quantity int) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  v_actor text := assert_admin();
  di donation_items;
  it items;
  v_status text;
begin
  select * into di from donation_items where id = p_donation_item_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  select * into it from items where id = di.item_id for update;
  select status into v_status from donations where id = di.donation_id;

  if p_quantity is null or p_quantity < 0 then raise exception 'INVALID_QTY'; end if;

  if p_quantity = 0 then
    if (select count(*) from donation_items where donation_id = di.donation_id) <= 1 then
      raise exception 'LAST_ITEM';
    end if;
    delete from donation_items where id = di.id;
  else
    if v_status = 'ativa' and item_committed(it.id) - di.quantity + p_quantity > it.limit_qty then
      raise exception 'OVER_LIMIT:%', it.id;
    end if;
    update donation_items set quantity = p_quantity where id = di.id;
  end if;

  insert into audit_log(actor, action, donation_id, details)
  values (v_actor, 'quantidade_alterada', di.donation_id,
          jsonb_build_object('item', it.name, 'de', di.quantity, 'para', p_quantity));
end $$;

create or replace function public.admin_update_donation_contact(
  p_id uuid, p_name text, p_email text, p_phone text, p_notes text
) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  v_actor text := assert_admin();
  v_old donations;
begin
  select * into v_old from donations where id = p_id;
  if not found then raise exception 'NOT_FOUND'; end if;
  p_phone := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  if length(btrim(coalesce(p_name, ''))) < 3 then raise exception 'INVALID_NAME'; end if;
  if length(p_phone) not between 10 and 13 then raise exception 'INVALID_PHONE'; end if;

  update donations
  set name = btrim(p_name), email = lower(btrim(p_email)), phone = p_phone, notes = nullif(btrim(p_notes), '')
  where id = p_id;

  insert into audit_log(actor, action, donation_id, details)
  values (v_actor, 'dados_editados', p_id, jsonb_build_object(
    'antes', jsonb_build_object('nome', v_old.name, 'email', v_old.email, 'telefone', v_old.phone, 'obs', v_old.notes),
    'depois', jsonb_build_object('nome', btrim(p_name), 'email', lower(btrim(p_email)), 'telefone', p_phone, 'obs', nullif(btrim(p_notes), ''))
  ));
end $$;

create or replace function public.admin_update_item(p_id int, p_limit int, p_active boolean) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  v_actor text := assert_admin();
  it items;
begin
  select * into it from items where id = p_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if p_limit is null or p_limit < item_committed(p_id) then
    raise exception 'LIMIT_BELOW_COMMITTED';
  end if;
  update items set limit_qty = p_limit, active = p_active where id = p_id;
  insert into audit_log(actor, action, details)
  values (v_actor, 'item_alterado', jsonb_build_object(
    'item', it.name, 'limite_de', it.limit_qty, 'limite_para', p_limit,
    'ativo_de', it.active, 'ativo_para', p_active));
end $$;

create or replace function public.admin_update_settings(p jsonb) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  v_actor text := assert_admin();
  v_old settings;
begin
  select * into v_old from settings where id = 1;
  update settings set
    form_open = coalesce((p ->> 'form_open')::boolean, form_open),
    closes_at = case when p ? 'closes_at' then nullif(p ->> 'closes_at', '')::timestamptz else closes_at end,
    delivery_deadline = coalesce(p ->> 'delivery_deadline', delivery_deadline),
    delivery_place = coalesce(p ->> 'delivery_place', delivery_place),
    morning_hours = coalesce(p ->> 'morning_hours', morning_hours),
    afternoon_hours = coalesce(p ->> 'afternoon_hours', afternoon_hours),
    pix_deadline = coalesce(p ->> 'pix_deadline', pix_deadline),
    pix_key = coalesce(p ->> 'pix_key', pix_key),
    contacts = coalesce(p -> 'contacts', contacts),
    updated_at = now()
  where id = 1;
  insert into audit_log(actor, action, details)
  values (v_actor, 'configuracoes_alteradas', jsonb_build_object('antes', to_jsonb(v_old), 'alteracoes', p));
end $$;

