create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

create or replace function public.assert_admin() returns text
language plpgsql stable security definer set search_path = public as $$
begin
  if not is_admin() then
    raise exception 'NOT_ADMIN' using errcode = '42501';
  end if;
  return lower(auth.jwt() ->> 'email');
end $$;

-- Quantidade já comprometida (doações ativas) de um item.
create or replace function public.item_committed(p_item int) returns int
language sql stable security definer set search_path = public as $$
  select coalesce(sum(di.quantity), 0)::int
  from donation_items di
  join donations d on d.id = di.donation_id
  where di.item_id = p_item and d.status = 'ativa';
$$;

-- Catálogo com saldo. Público: o formulário precisa saber o que ainda está disponível.
create or replace function public.get_catalog()
returns table (
  id int, category text, name text, limit_qty int, pix_price numeric,
  sort_order int, active boolean, committed int, received int, remaining int
)
language sql stable security definer set search_path = public as $$
  select i.id, i.category, i.name, i.limit_qty, i.pix_price, i.sort_order, i.active,
         coalesce(s.committed, 0)::int,
         coalesce(s.received, 0)::int,
         greatest(i.limit_qty - coalesce(s.committed, 0), 0)::int
  from items i
  left join (
    select di.item_id,
           sum(di.quantity) as committed,
           sum(di.quantity) filter (where di.received) as received
    from donation_items di
    join donations d on d.id = di.donation_id and d.status = 'ativa'
    group by di.item_id
  ) s on s.item_id = i.id
  order by i.sort_order, i.id;
$$;

-- =========================================================================
-- Envio público do formulário (transação com lock por item)
-- =========================================================================

create or replace function public.submit_donation(
  p_name text, p_email text, p_phone text, p_items jsonb
) returns table (donation_id uuid, protocol int)
language plpgsql volatile security definer set search_path = public as $$
#variable_conflict use_column
declare
  s settings;
  r record;
  it items;
  v_id uuid;
  v_protocol int;
begin
  select * into s from settings where id = 1;
  if not s.form_open or (s.closes_at is not null and now() > s.closes_at) then
    raise exception 'FORM_CLOSED';
  end if;

  p_name := btrim(coalesce(p_name, ''));
  p_email := lower(btrim(coalesce(p_email, '')));
  p_phone := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');

  if length(p_name) < 3 or length(p_name) > 120 then raise exception 'INVALID_NAME'; end if;
  if length(p_email) > 160 or p_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'INVALID_EMAIL'; end if;
  if length(p_phone) not between 10 and 13 then raise exception 'INVALID_PHONE'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'NO_ITEMS'; end if;
  if jsonb_array_length(p_items) > 50 then raise exception 'NO_ITEMS'; end if;

  -- Trava as linhas dos itens envolvidos (em ordem fixa, evitando deadlock):
  -- dois doadores disputando o último saldo são serializados aqui.
  perform 1 from items
  where id in (select (e ->> 'item_id')::int from jsonb_array_elements(p_items) e)
  order by id
  for update;

  -- Valida tudo antes de inserir, para não consumir números de protocolo em envios recusados.
  for r in
    select (e ->> 'item_id')::int as item_id, sum((e ->> 'quantity')::int)::int as qty
    from jsonb_array_elements(p_items) e
    group by 1
  loop
    if r.qty is null or r.qty <= 0 then raise exception 'INVALID_QTY'; end if;
    select * into it from items where id = r.item_id;
    if not found or not it.active then
      raise exception 'ITEM_UNAVAILABLE:%', r.item_id;
    end if;
    if item_committed(r.item_id) + r.qty > it.limit_qty then
      raise exception 'OVER_LIMIT:%', r.item_id;
    end if;
  end loop;

  insert into donations(name, email, phone)
  values (p_name, p_email, p_phone)
  returning id, donations.protocol into v_id, v_protocol;

  insert into donation_items(donation_id, item_id, quantity)
  select v_id, (e ->> 'item_id')::int, sum((e ->> 'quantity')::int)::int
  from jsonb_array_elements(p_items) e
  group by 2;

  insert into audit_log(actor, action, donation_id, details)
  values ('formulário', 'doacao_criada', v_id, jsonb_build_object('items', p_items));

  return query select v_id, v_protocol;
end $$;

