create table if not exists public.admins (
  email text primary key,
  created_at timestamptz not null default now()
);

create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  form_open boolean not null default true,
  closes_at timestamptz,
  delivery_deadline text not null default '14/12/2025',
  delivery_place text not null default 'Campus Expedicionários',
  morning_hours text not null default '08h00 às 12h00',
  afternoon_hours text not null default '14h00 às 18h00',
  pix_deadline text not null default '14/12/2025',
  pix_key text not null default 'institutovidaabencoada@gmail.com',
  contacts jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.items (
  id int generated by default as identity primary key,
  category text not null,
  name text not null unique,
  limit_qty int not null check (limit_qty >= 0),
  pix_price numeric(10,2),
  sort_order int not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.donations (
  id uuid primary key default gen_random_uuid(),
  protocol int generated by default as identity unique,
  name text not null,
  email text not null,
  phone text not null,
  status text not null default 'ativa' check (status in ('ativa', 'anulada')),
  notes text,
  voided_at timestamptz,
  voided_by text,
  void_reason text,
  created_at timestamptz not null default now()
);

create table if not exists public.donation_items (
  id uuid primary key default gen_random_uuid(),
  donation_id uuid not null references public.donations(id) on delete cascade,
  item_id int not null references public.items(id),
  quantity int not null check (quantity > 0),
  received boolean not null default false,
  received_at timestamptz,
  received_by text,
  unique (donation_id, item_id)
);

create table if not exists public.audit_log (
  id bigint generated always as identity primary key,
  actor text not null,
  action text not null,
  donation_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists donation_items_item_idx on public.donation_items(item_id);
create index if not exists donation_items_donation_idx on public.donation_items(donation_id);
create index if not exists donations_created_idx on public.donations(created_at desc);
create index if not exists audit_log_created_idx on public.audit_log(created_at desc);

